"""Rush Hour generator. 6x6, exit on the right of row 2. Car 0 = red (len 2, horizontal, row 2).
A move = slide one car any distance. For a random layout we BFS its whole state space,
then multi-source BFS from solved states to find the HARDEST start in that component."""
import random, json, sys, pathlib
from collections import deque
N=6
def occ(cars,pos):
    g=[[-1]*N for _ in range(N)]
    for i,(l,h,fixed) in enumerate(cars):
        x,y=pos[i]
        for k in range(l):
            cx,cy=(x+k,y) if h else (x,y+k)
            if g[cy][cx]!=-1: return None
            g[cy][cx]=i
    return g
def moves(cars,pos):
    g=occ(cars,pos);out=[]
    for i,(l,h,_) in enumerate(cars):
        x,y=pos[i]
        if h:
            for d in (-1,1):
                s=1
                while True:
                    nx=x+d*s
                    if nx<0 or nx+l>N: break
                    cx=nx if d<0 else nx+l-1
                    if g[y][cx]!=-1: break
                    p=list(pos);p[i]=(nx,y);out.append(tuple(p));s+=1
        else:
            for d in (-1,1):
                s=1
                while True:
                    ny=y+d*s
                    if ny<0 or ny+l>N: break
                    cy=ny if d<0 else ny+l-1
                    if g[cy][x]!=-1: break
                    p=list(pos);p[i]=(x,ny);out.append(tuple(p));s+=1
    return out
def solved(pos): return pos[0][0]==N-2
def hardest(cars,start,limit=60000):
    seen={start:None};q=deque([start]);adj={}
    while q:
        s=q.popleft();m=moves(cars,s);adj[s]=m
        for t in m:
            if t not in seen:
                seen[t]=1;q.append(t)
                if len(seen)>limit: return None
    sol=[s for s in seen if solved(s)]
    if not sol: return None
    dist={s:0 for s in sol};q=deque(sol)
    while q:
        s=q.popleft()
        for t in adj[s]:
            if t not in dist: dist[t]=dist[s]+1;q.append(t)
    best=max(dist,key=lambda s:dist[s])
    return best,dist[best],dist
def solve_path(cars,start):
    prev={start:None};q=deque([start])
    while q:
        s=q.popleft()
        if solved(s):
            path=[];
            while s is not None: path.append(s);s=prev[s]
            return path[::-1]
        for t in moves(cars,s):
            if t not in prev: prev[t]=s;q.append(t)
def rand_layout(rng,ncars):
    cars=[(2,True,False)];pos=[(rng.randrange(0,3),2)]
    tries=0
    while len(cars)<ncars and tries<400:
        tries+=1
        l=3 if rng.random()<0.3 else 2;h=rng.random()<0.5
        if h:
            y=rng.randrange(N)
            if y==2: continue
            x=rng.randrange(0,N-l+1)
        else:
            x=rng.randrange(N);y=rng.randrange(0,N-l+1)
        c=cars+[(l,h,False)];p=pos+[(x,y)]
        if occ(c,p) is not None: cars,pos=c,p
    return cars,tuple(pos)
def gen(targets,seed=7,budget=4000):
    rng=random.Random(seed);found={}
    for it in range(budget):
        cars,pos=rand_layout(rng,rng.randint(8,13))
        r=hardest(cars,pos)
        if not r: continue
        best,d,_=r
        for t in targets:
            if t not in found and t<=d<=t+3:
                found[t]=(cars,best,d)
        if len(found)==len(targets): break
    return found
